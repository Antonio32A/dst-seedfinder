static int math_min (lua_State *L) {
  int n = lua_gettop(L);  /* number of arguments */
  lua_Number dmin = luaL_checknumber(L, 1);
  int i;
  for (i=2; i<=n; i++) {
    lua_Number d = luaL_checknumber(L, i);
    if (d < dmin)
      dmin = d;
  }
  lua_pushnumber(L, dmin);
  return 1;
}


static int math_max (lua_State *L) {
  int n = lua_gettop(L);  /* number of arguments */
  lua_Number dmax = luaL_checknumber(L, 1);
  int i;
  for (i=2; i<=n; i++) {
    lua_Number d = luaL_checknumber(L, i);
    if (d > dmax)
      dmax = d;
  }
  lua_pushnumber(L, dmax);
  return 1;
}


/*
** DST (Don't Starve Together) replacement, reverse engineered from
** dontstarve_dedicated_server_nullrenderer_x64 (BuildID 9937c144...):
** Klei replaced libc srand/rand with PCG32 (pcg32_srandom_r / pcg32_random_r)
** kept in thread-local storage, and math.random divides the raw 32-bit PCG
** output by 4294967295.0 (so r can be exactly 1.0).
*/

#define DST_PCG_MULT 0x5851f42d4c957f2dULL
#define DST_PCG_DEFAULT_STATE 0x853c49e6748fea9bULL
#define DST_PCG_DEFAULT_INC 0xda3e39cb94b95bdbULL
#define DST_PCG_SEEDED_INC 0xb47c73972972b7b7ULL

unsigned long long dst_pcg_state = DST_PCG_DEFAULT_STATE;
unsigned long long dst_pcg_inc = DST_PCG_DEFAULT_INC;

/* binary srand @0x737780 */
void dst_srand (unsigned int seed) {
  dst_pcg_inc = DST_PCG_SEEDED_INC;
  dst_pcg_state = ((unsigned long long)seed + DST_PCG_SEEDED_INC) * DST_PCG_MULT
                  + DST_PCG_SEEDED_INC;
}

/* binary pcg32 step @0x7377c0 */
unsigned int dst_pcg32 (void) {
  unsigned long long old = dst_pcg_state;
  unsigned int xorshifted = (unsigned int)(((old >> 18) ^ old) >> 27);
  unsigned int rot = (unsigned int)(old >> 59);
  dst_pcg_state = old * DST_PCG_MULT + dst_pcg_inc;
  return (xorshifted >> rot) | (xorshifted << ((32 - rot) & 31));
}

/* binary rand @0x737810 (used by C++ WorldSim code, not by math.random) */
int dst_rand (void) {
  unsigned int x;
  do { x = dst_pcg32(); } while (x <= 1);
  return (int)(x % 2147483647u);
}

/* binary pcg32_boundedrand @0x737840/0x7378b0 (used by C++ WorldSim code) */
unsigned int dst_pcg32_bounded (unsigned int bound) {
  unsigned int threshold = (0u - bound) % bound;
  unsigned int x;
  do { x = dst_pcg32(); } while (x < threshold);
  return x % bound;
}

/* binary math_random @0x812f10 */
static int math_random (lua_State *L) {
  lua_Number r = (lua_Number)dst_pcg32() / 4294967295.0;
  switch (lua_gettop(L)) {
    case 0: {
      lua_pushnumber(L, r);
      break;
    }
    case 1: {
      int u = luaL_checkint(L, 1);
      luaL_argcheck(L, 1<=u, 1, "interval is empty");
      lua_pushnumber(L, floor(r*u)+1);
      break;
    }
    case 2: {
      int l = luaL_checkint(L, 1);
      int u = luaL_checkint(L, 2);
      luaL_argcheck(L, l<=u, 2, "interval is empty");
      lua_pushnumber(L, floor(r*(int)((unsigned int)u-(unsigned int)l+1u))+l);
      break;
    }
    default: return luaL_error(L, "wrong number of arguments");
  }
  return 1;
}

/* binary math_randomseed @0x812de0 */
static int math_randomseed (lua_State *L) {
  dst_srand((unsigned int)luaL_checkint(L, 1));
  return 0;
}


