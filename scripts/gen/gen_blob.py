#!/usr/bin/env python3
"""Writes data/blob.bend, the decoder of the data blob codec defined in lib/blob.py (`-` prints it instead)."""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent / "lib"))
import blob  # noqa: E402

text = "# Generated by scripts/gen/gen_blob.py; do not edit by hand.\n" + blob.BLOB_BEND.lstrip("\n")
if sys.argv[1:] == ["-"]:
    sys.stdout.write(text)
else:
    (blob.ROOT / "seedfinder" / "data" / "blob.bend").write_text(text)
