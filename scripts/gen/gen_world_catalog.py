#!/usr/bin/env python3
"""Generates data/world_catalog.bend: task numbering, level.set_pieces key table and random set pieces.

Run from the project root:
    python3 scripts/gen/gen_world_catalog.py    (writes seedfinder/data/world_catalog.bend; `-` prints it instead)
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
sys.path.insert(0, str(Path(__file__).resolve().parent / "lib"))
import blob  # noqa: E402
import model  # noqa: E402
from gen_catalog import BOONS, POI, PROTECTED, TRAPS  # noqa: E402

LITERAL_ORDER = ["Make a pick", "Dig that rock", "Great Plains", "Squeltch", "Beeeees!", "Speak to the king",
                 "Forest hunters", "Befriend the pigs", "For a nice walk", "Kill the spiders", "Killer bees!",
                 "Make a Beehat", "The hunters", "Magic meadow", "Frogs and bugs", "Badlands", "Lightning Bluff",
                 "Mole Colony Deciduous", "Mole Colony Rocks", "MooseBreedingTask", "MoonIsland_Mine",
                 "MoonIsland_Forest", "MoonIsland_IslandShards", "MoonIsland_Beach", "MoonIsland_Baths"]
TASK_ID = {name: i for i, name in enumerate(LITERAL_ORDER)}
AREAS = ["Any", "GRASS", "ROCKY", "SAVANNA", "FOREST", "MARSH", "DIRT", "DECIDUOUS"]


def area_code(area):
    return 0 if area in ("Any", "Rare") else AREAS.index(area)


def packed(values, width):
    return sum(v << (width * i) for i, v in enumerate(values))


def words(values, width):
    per = 32 // width
    return [packed(values[i:i + per], width) for i in range(0, len(values), per)]


def task_mask(names):
    return sum(1 << TASK_ID[n] for n in names if n in TASK_ID)


def keys():
    out = [(name, count, task_mask(tasks), 0) for name, count, tasks in model.TASKSET_SET_PIECES]
    for areas in (BOONS, TRAPS, POI, PROTECTED):
        for area, items, cave in areas:
            if not cave:
                out += [(item, 0, 0, area_code(area)) for item in items]
    return out


def check_forest_tables():
    """The hand-written forest tables of model.py against the extracted default task set and level."""
    story = blob.sidecar("story.json")
    taskset, level = story["taskset"], story["level"]
    assert sorted(model.REQUIRED_TASKS + model.MOON_TASKS) == sorted(taskset["tasks"])
    assert model.OPTIONAL_TASKS == taskset["optionaltasks"] and len(model.OPTIONAL_TASKS) == 10
    assert taskset["numoptionaltasks"] == 5
    assert {name: (count, tasks) for name, count, tasks in model.TASKSET_SET_PIECES} == {
        p["name"]: (p["count"], p["tasks"]) for p in taskset["set_pieces"]}
    assert model.REQUIRED_SET_PIECES == level["required_setpieces"]
    assert model.RANDOM_SET_PIECES == level["random_set_pieces"]


def check_order():
    check_forest_tables()
    for _, _, tasks in model.TASKSET_SET_PIECES:
        ids = [TASK_ID[t] for t in tasks if t in TASK_ID]
        assert ids == sorted(ids), tasks
    assert sorted(LITERAL_ORDER) == sorted(model.REQUIRED_TASKS + model.MOON_TASKS + model.OPTIONAL_TASKS)


def u32_match(name, arg, rows, result="U32", default="0"):
    lines = [f"def {name}(+{arg}: U32) -> {result}:", f"  match {arg}:"]
    for k, v in rows:
        lines += [f"    case {k}:", f"      {v}"]
    lines += ["    case _:", f"      {default}", ""]
    return "\n".join(lines)


def const(name, value, result="U32"):
    return f"def {name}() -> {result}:\n  {value}\n"


def quoted(s):
    return '"' + s + '"'


def names_list(name, pairs):
    rows = ",\n".join(f"    Name{{{quoted(n)}, {i}}}" for n, i in pairs)
    return f"def {name}() -> List<&2, Name>:\n  [\n{rows}\n  ]\n"


def main():
    check_order()
    table = keys()
    assert len(table) == 62
    base = model.taskset_set_pieces_table()
    key_id = {name: i + 1 for i, (name, _, _, _) in enumerate(table)}
    required = [TASK_ID[t] for t in model.REQUIRED_TASKS]
    moon = [TASK_ID[t] for t in model.MOON_TASKS]
    optional = [TASK_ID[t] for t in model.OPTIONAL_TASKS]
    backgrounds = [area_code(model.ROOM_BG[t]) for t in model.OPTIONAL_TASKS]
    area_required = [sum(1 << p for p, t in enumerate(model.REQUIRED_TASKS)
                         if code == 0 or area_code(model.ROOM_BG[t]) == code) for code in range(len(AREAS))]
    hashes = {name: model.lua_string_hash(name) & 31 for name, _, _, _ in table}

    out = ["# Generated by scripts/gen/gen_world_catalog.py; do not edit by hand.", "import Base", "",
           "type Name is Data:", "  Name{name: String, id: U32}", ""]
    out.append("# Task ids: every task list of the default task set's set_pieces is in increasing id order.")
    out.append(names_list("tasks", [(n, i) for i, n in enumerate(LITERAL_ORDER)]))
    out.append(u32_match("task_name", "id", [(i, quoted(n)) for i, n in enumerate(LITERAL_ORDER)], "String", '""'))
    for i, w in enumerate(words(required, 5)):
        out.append(const(f"required_tasks_{i}", w))
    out.append(const("moon_tasks", packed(moon, 5)))
    for i, w in enumerate(words(optional, 5)):
        out.append(const(f"optional_tasks_{i}", w))
    out.append(const("optional_backgrounds", packed(backgrounds, 3)))
    out.append(const("always_chosen", sum(1 << t for t in required + moon)))
    out.append("# Placeable (non-blocker) required tasks whose room_bg matches an area code (0 = Any/Rare).")
    out.append(u32_match("area_required", "area", list(enumerate(area_required))))
    out.append("# level.set_pieces keys: bits 0-4 Lua string hash mod 32, bits 5-7 area code, bits 8-11 task set count.")
    out.append(u32_match("key_info", "key", [(key_id[n], hashes[n] | area << 5 | count << 8)
                                             for n, count, _, area in table]))
    out.append(u32_match("fixed_tasks", "key", [(key_id[n], mask) for n, count, mask, _ in table if count]))
    out.append(u32_match("key_name", "key", [(key_id[n], quoted(n)) for n, _, _, _ in table], "String", '""'))
    out.append(const("first_boon_key", key_id[BOONS[0][1][0]]))
    out.append(const("first_trap_key", key_id["Sleeping Spider"] - 1))
    out.append(const("first_poi_key", key_id["skeleton_trapper"] - 1))
    out.append(const("first_protected_key", key_id["leif_forest"] - 1))
    out.append("# The task set's set_pieces table after deepcopy: node position -> key, and its lastfree.")
    writes = [f"  a[{p}] <- {key_id[k] | hashes[k] << 8}" for p, k in enumerate(base.nodes) if k]
    out.append("def base_nodes(a: Array<U32>) -> Array<U32>:\n" + "\n".join(writes) + "\n")
    out.append(const("base_last_free", base.last_free))
    out.append(const("base_count", len(base.keys())))
    specials = model.REQUIRED_SET_PIECES + model.RANDOM_SET_PIECES
    out.append("# Random set pieces: 0 and 1 are the level's required ones, 2.. index random_set_pieces.")
    out.append(u32_match("special_name", "code", [(i, quoted(n)) for i, n in enumerate(specials)], "String", '""'))
    out.append(const("special_piece", 64))
    out.append("# Every set piece name a filter may use: table keys by key id, random set pieces at special_piece() + code.")
    out.append(names_list("pieces", sorted([(n, key_id[n]) for n, _, _, _ in table]
                                           + [(n, 64 + i) for i, n in enumerate(specials)])))
    emit(out, "world_catalog.bend")


def emit(lines, name):
    """Writes the generated module to data/<name> in the project root, or to stdout with the argument `-`."""
    text = "\n".join(lines) + "\n"
    if sys.argv[1:] == ["-"]:
        sys.stdout.write(text)
        return
    (Path(__file__).resolve().parents[2] / "seedfinder" / "data" / name).write_text(text)


if __name__ == "__main__":
    main()
