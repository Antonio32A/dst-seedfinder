import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
const catalogPath = process.argv[2] ?? path.join(root, "scripts", "catalog", "catalog.json");
const outPath = path.join(root, "website", "lib", "catalog", "world.ts");
const catalog = JSON.parse(readFileSync(catalogPath, "utf8"));
const textures = JSON.parse(readFileSync(path.join(root, "scripts", "catalog", "map_textures.json"), "utf8"));
const iconRects = JSON.parse(readFileSync(path.join(root, "website", "public", "world-map", textures.iconSheet.rects), "utf8")).icons;
const textureUrl = (file) => `/world-map/${file}`;

const GROUP_ORDER = [
    "spawn & travel", "bosses & spawners", "landmarks", "clockwork", "sculptures", "statues", "trees", "rocks", "plants",
    "mobs & dens", "structures", "items", "set-piece loot", "ocean", "moon island", "markers", "other",
];

const ANCHORS = [
    ["multiplayer_portal", "Spawn (Florid Postern)"],
    ["pigking", "Pig King"],
    ["moonbase", "Moon Stone"],
    ["dragonfly_spawner", "Dragonfly"],
    ["beequeenhive", "Bee Queen (Gigantic Beehive)"],
    ["antlion_spawner", "Antlion"],
    ["crabking_spawner", "Crab King"],
    ["hermithouse_construction1", "Crabby Hermit (Pearl's house)"],
    ["monkeyqueen", "Queen of Moon Quay"],
    ["wormhole", "Worm Hole"],
];

const prefabIds = new Set(catalog.prefabs.map((prefab) => prefab.id));
const missingAnchors = ANCHORS.filter(([id]) => !prefabIds.has(id));
if (missingAnchors.length > 0) throw new Error(`anchors missing from the catalog: ${missingAnchors.join(", ")}`);
const groups = [...new Set(catalog.prefabs.map((prefab) => prefab.group))];
const orderedGroups = [...GROUP_ORDER.filter((group) => groups.includes(group)), ...groups.filter((group) => !GROUP_ORDER.includes(group))];

const titleCase = (name) => name.toLowerCase().split("_").map((word) => word.charAt(0).toUpperCase() + word.slice(1)).join(" ");

const iconRow = ({ element, priority, over_fog }) => {
    if (!(element in iconRects)) throw new Error(`no sprite sheet rect for the minimap icon ${element}`);
    const { x, y, w, h } = iconRects[element];
    return { x, y, w, h, ...(priority ? { priority } : {}), ...(over_fog ? { overFog: true } : {}) };
};

const prefabRow = ({ id, display_name, group, variant_of, default_reachable, default_shown, empirical, swap, icons }) => ({
    id,
    name: display_name,
    group,
    ...(variant_of ? { variantOf: variant_of } : {}),
    ...(default_reachable ? {} : { unreachable: true }),
    ...(default_shown ? { defaultShown: true } : {}),
    ...(empirical.always ? { always: true } : {}),
    ...(empirical.unique ? { unique: true } : {}),
    ...(empirical.worlds > 0 ? { counts: [empirical.min, empirical.median, empirical.max] } : {}),
    ...(swap ? { swapOption: swap.option } : {}),
    ...(icons.minimap ? { icon: iconRow(icons.minimap) } : {}),
});

const landTileRow = ({ name, display_name, in_forest_worlds }) => ({
    name,
    displayName: display_name ?? titleCase(name),
    ...((in_forest_worlds?.worlds ?? 0) > 0 ? { inDefaultWorlds: true } : {}),
});

const mapTileEntry = ({ name, display_name, class: kind, color, minimap_noise, minimap_rank, ocean_minimap_color }) => [
    name,
    {
        displayName: display_name ?? titleCase(name),
        kind,
        color,
        ...(minimap_noise ? { minimapNoise: textureUrl(textures.noise[minimap_noise]) } : {}),
        ...(minimap_rank ? { minimapRank: minimap_rank } : {}),
        ...(ocean_minimap_color ? { oceanMinimapColor: ocean_minimap_color } : {}),
    },
];

const MAX_LINE_LENGTH = 120;
const INDENT = "    ";

const literal = (value) => {
    if (Array.isArray(value)) return `[${value.map(literal).join(", ")}]`;
    if (value === null || typeof value !== "object") return JSON.stringify(value);
    return `{ ${Object.entries(value).map(([key, item]) => `${JSON.stringify(key)}: ${literal(item)}`).join(", ")} }`;
};

const line = (prefix, value, last) => {
    const end = last ? "" : ",";
    const single = `${INDENT}${prefix}${literal(value)}${end}`;
    if (single.length <= MAX_LINE_LENGTH) return single;
    const fields = Object.entries(value).map(([key, item]) => `${INDENT}${INDENT}${JSON.stringify(key)}: ${literal(item)}`);
    return `${INDENT}${prefix}{\n${fields.join(",\n")}\n${INDENT}}${end}`;
};

const rows = (items) => items.map((item, index) => line("", item, index === items.length - 1)).join("\n");
const entries = (pairs) => pairs.map(([key, value], index) => line(`${JSON.stringify(key)}: `, value, index === pairs.length - 1)).join("\n");

const source = `// Generated by scripts/gen/gen_website_catalog.mjs from scripts/catalog/catalog.json. Do not edit.
export const GAME_BUILD = ${Number(catalog.game_build)};
export const SAMPLE_WORLDS = ${catalog.worlds.total};

export const PREFAB_GROUP_IDS = ${literal(orderedGroups)} as const;
export type PrefabGroupId = (typeof PREFAB_GROUP_IDS)[number];

export interface WorldPrefab {
    id: string;
    name: string;
    group: PrefabGroupId;
    variantOf?: string;
    unreachable?: true;
    /** The game's map draws this prefab's icon in a freshly generated world. */
    defaultShown?: true;
    always?: true;
    unique?: true;
    counts?: [min: number, median: number, max: number];
    swapOption?: string;
    icon?: MapIcon;
}

/** The prefab's minimap icon: its UV rect on the sprite sheet in texels (top row first: u = x / width, v = y / height). */
export interface MapIcon {
    x: number;
    y: number;
    w: number;
    h: number;
    priority?: number;
    overFog?: true;
}

export interface PrefabGroup {
    id: PrefabGroupId;
    name: string;
    prefabs: string[];
}

export interface LandTile {
    name: string;
    displayName: string;
    inDefaultWorlds?: true;
}

export interface MapTile {
    displayName: string;
    kind: "land" | "ocean" | "impassable" | "invalid";
    color: [r: number, g: number, b: number];
    minimapNoise?: string;
    minimapRank?: number;
    oceanMinimapColor?: [r: number, g: number, b: number];
}

export interface NamedAnchor {
    id: string;
    label: string;
}

export const MAP_TEXTURES = {
    mapEdge: ${JSON.stringify(textureUrl(textures.mapEdge))},
    minimapPaper: ${JSON.stringify(textureUrl(textures.minimapPaper))},
    iconSheet: { url: ${JSON.stringify(textureUrl(textures.iconSheet.file))}, width: ${textures.iconSheet.width}, height: ${textures.iconSheet.height}, levels: ${JSON.stringify(textures.iconSheet.levels)} }
} as const;

export const PREFABS: WorldPrefab[] = [
${rows(catalog.prefabs.map(prefabRow))}
];

export const LAND_TILES: LandTile[] = [
${rows(catalog.tiles.filter((tile) => tile.land).map(landTileRow))}
];

export const NON_LAND_TILE_NAMES: string[] = ${literal(catalog.tiles.filter((tile) => !tile.land).map((tile) => tile.name))};

export const TILES: Readonly<Record<string, MapTile>> = {
${entries(catalog.tiles.map(mapTileEntry))}
};

export const NAMED_ANCHORS: NamedAnchor[] = [
${rows(ANCHORS.map(([id, label]) => ({ id, label })))}
];

export const PREFAB_BY_ID: ReadonlyMap<string, WorldPrefab> = new Map(PREFABS.map((prefab) => [prefab.id, prefab]));

export const PREFAB_GROUPS: PrefabGroup[] = PREFAB_GROUP_IDS.map((id) => ({
    id,
    name: id.charAt(0).toUpperCase() + id.slice(1),
    prefabs: PREFABS.filter((prefab) => prefab.group === id).map((prefab) => prefab.id)
}));

export const PREFAB_VARIANTS: ReadonlyMap<string, string[]> = PREFABS.reduce((variants, prefab) => {
    if (prefab.variantOf) variants.set(prefab.variantOf, [...(variants.get(prefab.variantOf) ?? []), prefab.id]);
    return variants;
}, new Map<string, string[]>());
`;

writeFileSync(outPath, source);
console.log(`${outPath}: ${catalog.prefabs.length} prefabs, ${orderedGroups.length} groups, ${catalog.tiles.filter((tile) => tile.land).length} land tiles, ${source.length} bytes`);
