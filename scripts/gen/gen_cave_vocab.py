#!/usr/bin/env python3
"""Generates website/lib/catalog/cave-vocab.ts: the caves shard's task and set piece ids with the structure the
website needs (kinds, counts, the tasks a set piece can go to), from the sidecars caves.json and layouts.json.

Run from the project root:
    python3 scripts/gen/gen_cave_vocab.py    (writes website/lib/catalog/cave-vocab.ts; `-` prints it instead)
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
sys.path.insert(0, str(Path(__file__).resolve().parent / "lib"))
import blob  # noqa: E402
from gen_cave_catalog import SANDBOXES, Catalog  # noqa: E402

OUTPUT = Path(__file__).resolve().parents[2] / "website" / "lib" / "catalog" / "cave-vocab.ts"
KINDS = {"traps": "trap", "pointsofinterest": "poi", "protected_resources": "protected", "boons": "boon"}
MOST_BOONS = 8


def js(value):
    return json.dumps(value, ensure_ascii=False)


def js_list(values):
    return "[" + ", ".join(js(v) for v in values) + "]"


def pieces(cat):
    found = {}
    for name, piece in cat.fixed.items():
        found[name] = {"id": name, "kind": "fixed", "rare": False, "maxCount": piece["count"],
                       "fixedCount": piece["count"], "tasks": list(piece["tasks"])}
    for fn, kind in SANDBOXES:
        for area in cat.sandboxes[kind]:
            if not cat.placeable(area["area"]):
                continue
            hosts = None if area["area"] in ("Any", "Rare") else [t for t in cat.tasks if cat.bg[t] == area["area"]]
            for name in area["pieces"]:
                entry = found.setdefault(name, {"id": name, "kind": KINDS[kind], "rare": False,
                                                "maxCount": MOST_BOONS if kind == "boons" else 1, "tasks": []})
                entry["rare"] = entry["rare"] or area["area"] == "Rare"
                if hosts is None or entry["tasks"] is None:
                    entry["tasks"] = None
                else:
                    entry["tasks"] = entry["tasks"] + [t for t in hosts if t not in entry["tasks"]]
    return list(found.values())


def piece_line(piece):
    fields = [f"id: {js(piece['id'])}", f"kind: {js(piece['kind'])}", f"rare: {js(piece['rare'])}",
              f"maxCount: {piece['maxCount']}"]
    if "fixedCount" in piece:
        fields.append(f"fixedCount: {piece['fixedCount']}")
    if piece["tasks"] is not None:
        fields.append(f"candidateTasks: {js_list(piece['tasks'])}")
    return "    { " + ", ".join(fields) + " }"


def generate():
    cat = Catalog(blob.sidecar("caves.json"), blob.sidecar("layouts.json"))
    swaps = [{"category": s["category"], "options": [o["name"] for o in s["sets"] if o["valid"]]}
             for s in cat.caves["prefab_swaps"]]
    lines = ["// Generated by scripts/gen/gen_cave_vocab.py from the caves sidecar (scripts/gen/extract_caves.lua). Do not edit.",
             f"export const CAVE_REQUIRED_TASK_IDS: readonly string[] = {js_list(cat.required)};",
             f"export const CAVE_OPTIONAL_TASK_IDS: readonly string[] = {js_list(cat.optional)};",
             f"export const CAVE_OPTIONAL_PICKED = {cat.picked};", "",
             "export type CavePieceKind = \"boon\" | \"trap\" | \"poi\" | \"protected\" | \"fixed\";", "",
             "export interface CavePieceVocab {", "    id: string;", "    kind: CavePieceKind;", "    rare: boolean;",
             "    maxCount: number;", "    fixedCount?: number;", "    candidateTasks?: readonly string[];", "}", "",
             "export const CAVE_PIECES: readonly CavePieceVocab[] = [",
             ",\n".join(piece_line(p) for p in pieces(cat)), "];", "",
             "export const CAVE_SWAPS: readonly { category: string; options: readonly string[] }[] = [",
             ",\n".join(f"    {{ category: {js(s['category'])}, options: {js_list(s['options'])} }}" for s in swaps),
             "];"]
    return "\n".join(lines) + "\n"


def main():
    text = generate()
    if sys.argv[1:] == ["-"]:
        sys.stdout.write(text)
    else:
        OUTPUT.write_text(text, encoding="utf-8")


if __name__ == "__main__":
    main()
