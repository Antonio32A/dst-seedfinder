#!/usr/bin/env python3
"""Generates data/catalog.bend (sandbox tables + set piece names) from the worldgen pairs() orders.

Area and item orders are stock Lua 5.1.5 pairs() order (traced under the harness, confirmed
identical to the game binary). Run from the project root:
    python3 scripts/gen/gen_catalog.py    (writes seedfinder/data/catalog.bend; `-` prints it instead)
"""
import sys
from pathlib import Path

TRAPS = [
    ("GRASS", [], False), ("FOREST", ["Sleeping Spider"], False), ("MARSH", ["Rotted Base"], False),
    ("ROCKY", [], False), ("SAVANNA", ["Beefalo Farm"], False), ("DIRT", [], False),
    ("Any", ["Fire Hounds", "Ice Hounds"], False), ("Rare", ["Dev Graveyard"], False),
]
POI = [
    ("FUNGUSRED", ["skeleton_mushjack"], True), ("FUNGUSGREEN", ["skeleton_mushjack"], True),
    ("FOREST", ["skeleton_trapper", "skeleton_lumberjack"], False), ("FUNGUS", ["skeleton_mushjack"], True),
    ("DIRT", ["skeleton_miner_dirt"], False), ("MARSH", ["skeleton_hunter_swamp"], False),
    ("Rare", ["skeleton_researchlab1", "skeleton_researchlab3", "skeleton_researchlab2", "skeleton_dapper"], False),
    ("MUD", ["skeleton_lightfarmer"], True), ("SAVANNA", ["skeleton_camper", "skeleton_hunter"], False),
    ("SINKHOLE", ["skeleton_lumberjack", "skeleton_farmer", "skeleton_entomologist"], True),
    ("CAVE", ["skeleton_miner", "skeleton_batfight"], True), ("ROCKY", ["skeleton_miner"], False),
    ("GRASS", ["grass_spots", "skeleton_farmer", "skeleton_entomologist"], False),
    ("Any", ["skeleton_warrior", "skeleton_wizard_ice", "skeleton_wizard_fire", "skeleton_rain_coat",
             "skeleton_fisher", "skeleton_graverobber", "skeleton_night_hunter", "skeleton_construction",
             "skeleton_summer"], False),
    ("UNDERROCK", ["skeleton_miner"], True),
]
PROTECTED = [
    ("FUNGUSRED", [], False), ("FUNGUSGREEN", [], False), ("FOREST", ["leif_forest", "spider_forest"], False),
    ("FUNGUS", [], False), ("DIRT", ["hound_rocks"], False), ("MARSH", ["tenticle_reeds"], False),
    ("Rare", [], False), ("MUD", ["lures_and_worms"], True), ("SAVANNA", ["pigguard_grass_easy", "pigguard_grass"], False),
    ("SINKHOLE", [], False), ("CAVE", [], False), ("ROCKY", ["tallbird_rocks"], False),
    ("GRASS", ["pigguard_berries_easy", "wasphive_grass_easy", "pigguard_berries"], False),
    ("Any", [], False), ("UNDERROCK", [], False),
]
BOONS = [
    ("Any", ["FishingBoon", "CookingBoon", "Level2GrassBoon", "MiscBoon", "Level2TwigsBoon", "Level2WoodBoon",
             "GrassBoon", "FarmingBoon", "WeaponBoon", "WoodBoon", "Level2RockBoon", "RockBoon", "TwigsBoon"], False),
    ("Rare", ["Level4Boon"], False),
]
FIXED = {
    "BathbombedHotspring": 1, "CaveEntrance": 10, "MoonAltarRockGlass": 1, "MoonAltarRockIdol": 1,
    "MoonAltarRockSeed": 1, "MoonFissures": 1, "MooseNest": 9, "ResurrectionStone": 2, "WormholeGrass": 8,
}
KIND_FIXED, KIND_BOON, KIND_TRAP, KIND_POI, KIND_PROTECTED = range(5)


def nibbles(values):
    assert len(values) <= 16 and all(0 <= v < 16 for v in values)
    padded = values + [0] * (16 - len(values))
    lo = sum(v << (4 * i) for i, v in enumerate(padded[:8]))
    hi = sum(v << (4 * i) for i, v in enumerate(padded[8:]))
    return lo, hi


def sandbox(name, areas):
    sizes = [len(items) for _, items, _ in areas]
    ids = [0 if cave else len(items) for _, items, cave in areas]
    rare = next(i for i, (area, _, _) in enumerate(areas) if area == "Rare")
    sizes_lo, sizes_hi = nibbles(sizes)
    ids_lo, ids_hi = nibbles(ids)
    names = [item for _, items, cave in areas if not cave for item in items]
    assert len(names) < 32
    body = (f"def {name}() -> Sandbox:\n"
            f"  Sandbox{{{len(areas)}, {rare}, {sizes_lo}, {sizes_hi}, {ids_lo}, {ids_hi}}}\n")
    return body, names


def main():
    out = ["# Generated by scripts/gen/gen_catalog.py; do not edit by hand.",
           "import Base", "",
           "# Areas in pairs() order; sizes and ids are 4-bit fields (8 per word), ids exclude cave areas.",
           "type Sandbox is Data:",
           "  Sandbox{areas: U32, rare: U32, sizes_lo: U32, sizes_hi: U32, ids_lo: U32, ids_hi: U32}", "",
           "type Entry is Data:", "  Entry{name: String, kind: U32, index: U32}", ""]
    entries = {name: (KIND_FIXED, count) for name, count in FIXED.items()}
    for fn, kind, areas in (("traps", KIND_TRAP, TRAPS), ("points_of_interest", KIND_POI, POI),
                            ("protected_resources", KIND_PROTECTED, PROTECTED), ("boons", KIND_BOON, BOONS)):
        body, names = sandbox(fn, areas)
        out.append(body)
        for i, item in enumerate(names):
            assert item not in entries, item
            entries[item] = (kind, i if kind == KIND_BOON else i + 1)
    for kind, name in ((KIND_FIXED, "fixed"), (KIND_BOON, "boon"), (KIND_TRAP, "trap"),
                       (KIND_POI, "point_of_interest"), (KIND_PROTECTED, "protected_resource")):
        out.append(f"def kind_{name}() -> U32:\n  {kind}\n")
    out.append("# Every set piece of the default forest, sorted by name (the order used for output).")
    out.append("def catalog() -> List<&2, Entry>:")
    rows = [f'    Entry{{"{name}", {kind}, {index}}}' for name, (kind, index) in sorted(entries.items())]
    out.append("  [\n" + ",\n".join(rows) + "\n  ]")
    emit(out, "catalog.bend")


def emit(lines, name):
    """Writes the generated module to data/<name> in the project root, or to stdout with the argument `-`."""
    text = "\n".join(lines) + "\n"
    if sys.argv[1:] == ["-"]:
        sys.stdout.write(text)
        return
    (Path(__file__).resolve().parents[2] / "seedfinder" / "data" / name).write_text(text)


if __name__ == "__main__":
    main()
