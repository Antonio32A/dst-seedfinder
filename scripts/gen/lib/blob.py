"""Codec for the generated Bend data modules.

A row is a Bend String literal whose characters each carry one 20-bit unit u as the code point 0x10000 + u, so the
checker and the compiler treat it as one cheap literal, and the compiler puts it in the static image. A table is a list
of rows in chunks of CHUNK_ROWS rows, one constant List of row Strings per chunk (a match with fewer cases: the
checker's cost grows with their number), so a lookup walks to its row's String and decodes only that row.
data/blob.bend (written by gen_blob.py from BLOB_BEND below) decodes rows into List<&2, U32>.

Conventions for values inside rows: 16-bit halves for U32 (hi, lo) and 4 halves for f64 bits (hi-hi, hi-lo, lo-hi,
lo-lo); signed values in 20-bit two's complement; strings as a byte count followed by bytes packed 2 per unit.
"""
import json
import os
import struct
import sys
from pathlib import Path

UNIT_BITS = 20
UNIT_LIMIT = 1 << UNIT_BITS
CHUNK_SHIFT = 5
CHUNK_ROWS = 1 << CHUNK_SHIFT
NONE = UNIT_LIMIT - 1

ROOT = Path(__file__).resolve().parents[3]
GEN = ROOT / "scripts" / "gen"


def out_dir():
    """Directory of the extractor sidecars (GEN_OUT overrides it, as regen.sh --check does)."""
    return Path(os.environ.get("GEN_OUT", GEN / "out"))


def sidecar(name):
    return json.loads((out_dir() / name).read_text())


def unit(v):
    assert isinstance(v, int) and 0 <= v < UNIT_LIMIT, v
    return v


def signed(v):
    assert -(UNIT_LIMIT >> 1) <= v < (UNIT_LIMIT >> 1), v
    return v & (UNIT_LIMIT - 1)


def word(v):
    assert 0 <= v < 1 << 32, v
    return [v >> 16, v & 0xFFFF]


def f64_bits(x):
    return struct.unpack(">Q", struct.pack(">d", float(x)))[0]


def f64(x):
    bits = f64_bits(x)
    return [(bits >> 48) & 0xFFFF, (bits >> 32) & 0xFFFF, (bits >> 16) & 0xFFFF, bits & 0xFFFF]


def f32_bits(x):
    return struct.unpack(">I", struct.pack(">f", float(x)))[0]


def text(s):
    data = s.encode("utf-8")
    padded = data + (b"\0" if len(data) % 2 else b"")
    return [len(data)] + [padded[i] << 8 | padded[i + 1] for i in range(0, len(padded), 2)]


def row_literal(row):
    return '"' + "".join(chr(0x10000 + unit(v)) for v in row) + '"'


def chunk_literal(rows):
    return "[" + ", ".join(row_literal(r) for r in rows) + "]"


class Module:
    """One generated data/<name>.bend file: constants, tables and hand-written accessor templates."""

    def __init__(self, name, generator, summary, imports=("./blob.bend as Blob",)):
        self.name = name
        self.lines = [f"# Generated by {generator}; do not edit by hand.", f"# {summary}", "import Base"]
        self.lines += [f"import {i}" for i in imports]
        self.lines.append("")
        self.tables = {}
        self.shifts = {}

    def comment(self, *lines):
        self.lines += [f"# {line}" if line else "#" for line in lines]

    def const(self, name, value, result="U32"):
        self.lines += [f"def {name}() -> {result}:", f"  {value}", ""]

    def code(self, text):
        self.lines += text.strip("\n").split("\n") + [""]

    def table(self, name, rows, doc=None, shift=CHUNK_SHIFT):
        """Table `name` with 2^shift rows per chunk: `name(i)` is row i, Nil past the end. Hand-written code may call
        `name_at(i, j)`, unit j of row i read without decoding the row: text() emits it for the tables that use it."""
        rows = [list(r) for r in rows]
        if doc:
            self.comment(doc)
        self.tables[name] = rows
        self.const(f"{name}_count", len(rows))
        per = 1 << shift
        self.lines += [f"def {name}_chunk(+c: U32) -> List<&2, String>:", "  match c:"]
        for c in range(0, len(rows), per):
            self.lines += [f"    case {c // per}:", f"      {chunk_literal(rows[c:c + per])}"]
        self.lines += ["    case _:", "      Nil{}", ""]
        self.lines += [f"def {name}(+i: U32) -> List<&2, U32>:",
                       f"  Blob.row({name}_chunk((i >> {shift}n : U32)), (i .&. {per - 1} : U32))", ""]
        self.shifts[name] = (shift, len(self.lines))

    def values(self, name, values, doc, past):
        """Table `name` of U32 values in constant chunks of CHUNK_ROWS (no decoding): `name(i)`, `past` past the end."""
        self.comment(doc)
        self.lines += [f"def {name}_chunk(+c: U32) -> List<&2, U32>:", "  match c:"]
        for c in range(0, len(values), CHUNK_ROWS):
            self.lines += [f"    case {c // CHUNK_ROWS}:", "      [" + ", ".join(str(v) for v in values[c:c + CHUNK_ROWS]) + "]"]
        self.lines += ["    case _:", "      Nil{}", ""]
        self.lines += [f"def {name}(+i: U32) -> U32:",
                       f"  Blob.value({name}_chunk((i >> {CHUNK_SHIFT}n : U32)), (i .&. {CHUNK_ROWS - 1} : U32), {past})", ""]

    def text(self):
        lines = list(self.lines)
        body = "\n".join(lines)
        for name, (shift, end) in sorted(self.shifts.items(), key=lambda item: -item[1][1]):
            if f"{name}_at(" in body:
                lines[end:end] = [f"def {name}_at(+i: U32, +j: U32) -> U32:",
                                  f"  Blob.row_at({name}_chunk((i >> {shift}n : U32)), (i .&. {(1 << shift) - 1} : U32), j)", ""]
        return "\n".join(lines).rstrip("\n") + "\n"

    def emit(self):
        """Writes data/<name>.bend, or prints it with the single argument `-`."""
        text = self.text()
        if sys.argv[1:] == ["-"]:
            sys.stdout.write(text)
            return
        (ROOT / "seedfinder" / "data" / f"{self.name}.bend").write_text(text)


def parse_module_tables(text):
    """Reads every table of a generated module back from its Bend text: {name: rows}."""
    tables, current = {}, None
    for line in text.split("\n"):
        if line.startswith("def ") and line.endswith("_chunk(+c: U32) -> List<&2, String>:"):
            current = line[4:line.index("_chunk(")]
            tables[current] = []
        elif current is not None and line.startswith('      ["'):
            tables[current] += [[ord(ch) - 0x10000 for ch in r] for r in json.loads(line.strip())]
        elif line.startswith("def ") and current is not None and not line.startswith(f"def {current}_chunk"):
            current = None
    return tables


BLOB_BEND = '''
# Decoder for the generated data tables (scripts/gen/lib/blob.py): chunks of rows, a row a String whose characters
# carry one 20-bit unit each (code point 0x10000 + unit).
import Base

def unit(c: Char) -> U32:
  (Char.to_u32(c) - 65536 : U32)

def units(s: String) -> List<&2, U32>:
  match s:
    case SNil{}:
      Nil{}
    case SCon{h, t}:
      unit(h) <> units(t)

def row_nat(n: Nat, rows: List<&2, String>) -> List<&2, U32>:
  match n rows:
    case _ Nil{}:
      Nil{}
    case 0n Con{r, _}:
      units(r)
    case 1n+p Con{_, t}:
      row_nat(p, t)

def unit_nat(n: Nat, s: String) -> U32:
  match n s:
    case _ SNil{}:
      1048575
    case 0n SCon{h, _}:
      unit(h)
    case 1n+p SCon{_, t}:
      unit_nat(p, t)

def row_at_nat(n: Nat, rows: List<&2, String>, +j: U32) -> U32:
  match n rows:
    case _ Nil{}:
      1048575
    case 0n Con{r, _}:
      unit_nat(U32.to_nat(j), r)
    case 1n+p Con{_, t}:
      row_at_nat(p, t, j)

# Unit j of row k of a chunk without decoding the row (1048575, the NONE unit, past either end).
def row_at(rows: List<&2, String>, +k: U32, +j: U32) -> U32:
  row_at_nat(U32.to_nat(k), rows, j)

# Row k of a chunk, decoded (Nil past its end).
def row(rows: List<&2, String>, +k: U32) -> List<&2, U32>:
  row_nat(U32.to_nat(k), rows)

def value_nat(n: Nat, xs: List<&2, U32>, +past: U32) -> U32:
  match n xs:
    case _ Nil{}:
      past
    case 0n Con{h, _}:
      h
    case 1n+p Con{_, t}:
      value_nat(p, t, past)

# Entry k of a chunk of values (`past` past its end).
def value(xs: List<&2, U32>, +k: U32, +past: U32) -> U32:
  value_nat(U32.to_nat(k), xs, past)

def at_nat(n: Nat, xs: List<&2, U32>) -> U32:
  match n xs:
    case 0n Nil{}:
      1048575
    case 0n Con{h, t}:
      h
    case 1n+p Nil{}:
      1048575
    case 1n+p Con{h, t}:
      at_nat(p, t)

# Unit j of a row (1048575, the NONE unit, past its end).
def at(xs: List<&2, U32>, +j: U32) -> U32:
  at_nat(U32.to_nat(j), xs)

def drop_nat(n: Nat, xs: List<&2, U32>) -> List<&2, U32>:
  match n xs:
    case 0n rest:
      rest
    case 1n+p Nil{}:
      Nil{}
    case 1n+p Con{h, t}:
      drop_nat(p, t)

# The row without its first j units.
def drop(xs: List<&2, U32>, +j: U32) -> List<&2, U32>:
  drop_nat(U32.to_nat(j), xs)

def first_nat(n: Nat, xs: List<&2, U32>) -> List<&2, U32>:
  match n xs:
    case 0n rest:
      Nil{}
    case 1n+p Nil{}:
      Nil{}
    case 1n+p Con{+h, t}:
      h <> first_nat(p, t)

# The first j units of a row.
def first(xs: List<&2, U32>, +j: U32) -> List<&2, U32>:
  first_nat(U32.to_nat(j), xs)

# The unit meaning "absent".
def none() -> U32:
  1048575

def is_none(+u: U32) -> Bool:
  U32.is_eq(u, 1048575)

# A 20-bit two's complement unit as a 32-bit two's complement U32.
def signed(+u: U32) -> U32:
  (u + ((u >> 19n) * 4293918720 : U32) : U32)

# Units j (high half) and j + 1 (low half) as one U32.
def word(xs: List<&2, U32>, +j: U32) -> U32:
  +rest = drop(xs, j)
  ((at(rest, 0) << 16n) .|. at(rest, 1) : U32)

# Units j .. j + 3 as the (hi, lo) words of an f64.
def f64(xs: List<&2, U32>, +j: U32) -> U32 & U32:
  +rest = drop(xs, j)
  (((at(rest, 0) << 16n) .|. at(rest, 1) : U32), ((at(rest, 2) << 16n) .|. at(rest, 3) : U32))

def text_go(n: Nat, xs: List<&2, U32>) -> String:
  match n xs:
    case 0n rest:
      SNil{}
    case 1n+p Nil{}:
      SNil{}
    case 1n+0n Con{+u, t}:
      SCon{Chr{(u >> 8n : U32)}, SNil{}}
    case 2n+p Con{+u, t}:
      SCon{Chr{(u >> 8n : U32)}, SCon{Chr{(u .&. 255 : U32)}, text_go(p, t)}}

# A string stored as its byte count followed by the bytes packed two per unit.
def text(xs: List<&2, U32>) -> String:
  match xs:
    case Nil{}:
      SNil{}
    case Con{+n, t}:
      text_go(U32.to_nat(n), t)
'''


def random_threshold(p):
    """The least x with x / (2^32 - 1) >= p in double arithmetic, so that `math.random() < p` is `x < threshold`."""
    lo, hi = 0, 1 << 32
    while lo < hi:
        mid = (lo + hi) // 2
        if mid / 4294967295.0 >= p:
            hi = mid
        else:
            lo = mid + 1
    return lo
