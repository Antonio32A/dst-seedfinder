#!/usr/bin/env python3
"""Writes seedfinder/data/ from the modules regen.sh staged for each game build of builds.json (build/gen/data/<build>/),
and website/lib/config/game-builds.ts:

- SINGLE modules, the same for every build: written as staged; fails naming a module that differs between builds.
- Every other module: one copy per distinct content in b<build>/ (named after the first build of builds.json with that
  content, its `./` imports made `../`), and a dispatch module <module>.bend with the copy's defs (but the `_chunk`
  tables), each taking the game build first (`+build: Builds.Build`). A build gets its own copy, any other number the
  latest build's. A module with one copy is called directly; with more, through `<def>_of_number(+number: U32, ...)`.
- builds.bend: the Build type and the registry (latest, of_number, number, numbers, numbers_text, has_caves).

usage: gen_builds.py [--staging DIR] [--root DIR]
(--root is where seedfinder/data/ and website/ are written, the repository by default; regen.sh --check passes a temp dir)
"""
import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent / "lib"))
import registry  # noqa: E402

SINGLE = ("blob", "pow", "powf", "enums", "tile_groups", "ocean", "ocean_convert", "constants", "catalog_types",
          "world_catalog_types", "cave_catalog_types", "search_vocab_types")
HEADER = "# Generated by scripts/gen/gen_builds.py; do not edit by hand."
DEF = re.compile(r"^def (\w+)\((.*)\) -> (.+):$")
IMPORT = re.compile(r"^import \./(\w+)\.bend as (\w+)$")
HELPER = "_of_number"


def camel(name):
    return "".join(part.capitalize() for part in name.split("_"))


def params(text):
    """The parameters of a def signature, split at the commas outside <> and ()."""
    found, depth, current = [], 0, ""
    for ch in text:
        depth += (ch in "<(") - (ch in ">)" and not current.endswith("-"))
        if ch == "," and depth == 0:
            found.append(current.strip())
            current = ""
        else:
            current += ch
    return found + ([current.strip()] if current.strip() else [])


def signatures(module, text):
    """{def name: (parameters, result)} of a staged module, in order, without its `_chunk` tables."""
    found = {}
    for line in text.split("\n"):
        if line.startswith("def "):
            match = DEF.match(line)
            assert match, f"{module}: a def gen_builds.py cannot read: {line}"
            if not match.group(1).endswith("_chunk"):
                found[match.group(1)] = (params(match.group(2)), match.group(3))
    return found


def staged(staging, numbers):
    """{module: {build: text}} of every staged module; fails unless every build staged the same modules."""
    modules = {}
    for number in numbers:
        for path in sorted((staging / str(number)).glob("*.bend")):
            modules.setdefault(path.stem, {})[number] = path.read_text(encoding="utf-8")
    for module, texts in modules.items():
        assert len(texts) == len(numbers), f"{module}: staged for builds {sorted(texts)} only, not {numbers}"
    return modules


def single(module, texts):
    if len(set(texts.values())) > 1:
        sys.exit(f"gen_builds.py: {module}.bend differs between builds {sorted(texts)}; it must be one module for all "
                 f"builds (split it into a per-build module)")
    return next(iter(texts.values()))


def copy_text(module, text):
    """A per-build copy: the staged module with its imports one folder up, which may name only SINGLE modules."""
    lines = []
    for line in text.split("\n"):
        match = IMPORT.match(line)
        if match:
            assert match.group(1) in SINGLE, f"{module}: a per-build module may not import {match.group(1)}"
            line = f"import ../{match.group(1)}.bend as {match.group(2)}"
        lines.append(line)
    return "\n".join(lines)


def copies(numbers, texts):
    """[(folder build, copy text, builds using it)] in builds.json order."""
    found = []
    for number in numbers:
        for folder, text, users in found:
            if text == texts[number]:
                users.append(number)
                break
        else:
            found.append((number, texts[number], [number]))
    return found


def type_imports(text):
    """The copy's imports of types modules, from the dispatch module's folder."""
    return [line.replace("import ../", "import ./") for line in text.split("\n")
            if line.startswith("import ../") and line.split(" as ")[0].endswith("_types.bend")]


def call(alias, name, args):
    return f"{alias}.{name}({', '.join(args)})"


def dispatch_def(name, signature, aliases, latest):
    """The dispatch of one def: aliases is [(copy alias, builds using it)]."""
    parameters, result = signature
    args = [p.split(":", 1)[0].strip().lstrip("+-") for p in parameters]
    head = ", ".join(["+build: Builds.Build"] + parameters)
    if len(aliases) == 1:
        return [f"def {name}({head}) -> {result}:", f"  {call(aliases[0][0], name, args)}", ""]
    default = next(alias for alias, users in aliases if latest in users)
    lines = [f"def {name}{HELPER}({', '.join(['+number: U32'] + parameters)}) -> {result}:", "  match number:"]
    for alias, users in aliases:
        if alias != default:
            for number in users:
                lines += [f"    case {number}:", f"      {call(alias, name, args)}"]
    lines += ["    case _:", f"      {call(default, name, args)}", ""]
    lines += [f"def {name}({head}) -> {result}:", "  match build:", "    case Builds.Build{+number}:",
              f"      {name}{HELPER}({', '.join(['number'] + args)})", ""]
    return lines


def dispatch(module, found, latest):
    """The dispatch module of a per-build module with the copies `found`."""
    aliases = [(f"B{folder}{camel(module)}", users) for folder, _, users in found]
    defs = signatures(module, found[0][1])
    for folder, text, _ in found[1:]:
        assert signatures(module, text) == defs, f"{module}: b{folder}/{module}.bend has other defs than b{found[0][0]}"
    names = set(defs) | {name + HELPER for name in defs if len(found) > 1}
    assert len(names) == len(defs) * (1 + (len(found) > 1)), f"{module}: a def is named like a {HELPER} dispatch"
    copies_text = ", ".join(f"b{folder} ({', '.join(map(str, users))})" for folder, _, users in found)
    lines = [HEADER, f"# The defs of b*/{module}.bend, each taking the game build first.",
             f"# Copies: {copies_text}; any other number uses the latest build's ({latest}).",
             "import Base", "import ./builds.bend as Builds"]
    lines += type_imports(found[0][1])
    lines += [f"import ./b{folder}/{module}.bend as {alias}" for (folder, _, _), (alias, _) in zip(found, aliases)]
    lines.append("")
    for name, signature in defs.items():
        lines += dispatch_def(name, signature, aliases, latest)
    return "\n".join(lines).rstrip("\n") + "\n"


def numbers_text(numbers):
    words = [str(n) for n in numbers]
    return words[0] if len(words) == 1 else ", ".join(words[:-1]) + " or " + words[-1]


def builds_bend(entries, latest):
    numbers = [b["number"] for b in entries]
    lines = ["# Generated by scripts/gen/gen_builds.py from builds.json; do not edit by hand.",
             "# The game builds the seed finder generates worlds for.", "import Base", "",
             "type Build is Data:", "  Build{number: U32}", "",
             "# The latest public build, the default one.", "def latest() -> Build:", f"  Build{{{latest}}}", "",
             "# The registered build with this number (None for any other number).",
             "def of_number(+n: U32) -> Maybe<&2, Build>:", "  match n:"]
    for number in numbers:
        lines += [f"    case {number}:", f"      Some{{Build{{{number}}}}}"]
    lines += ["    case _:", "      None{}", "",
              "def number(+build: Build) -> U32:", "  match build:", "    case Build{+number}:", "      number", "",
              "# Every registered build number, in builds.json order.", "def numbers() -> List<&2, U32>:",
              f"  [{', '.join(map(str, numbers))}]", "",
              "# The registered build numbers as messages list them.", "def numbers_text() -> String:",
              f"  \"{numbers_text(numbers)}\"", "", "def has_caves_of_number(+number: U32) -> Bool:", "  match number:"]
    for entry in entries:
        if "caves" in entry["shards"]:
            lines += [f"    case {entry['number']}:", "      True{}"]
    lines += ["    case _:", "      False{}", "", "# Whether the build's caves shard is supported.",
              "def has_caves(+build: Build) -> Bool:", "  has_caves_of_number(number(build))"]
    return "\n".join(lines) + "\n"


def ts_list(values):
    return "[" + ", ".join(f'"{v}"' for v in values) + "]"


def game_builds_ts(entries, latest):
    rows = [f'    {{ number: {b["number"]}, channel: "{b["channel"]}", '
            f'steamBranch: "{b["steam_branch"]}", shards: {ts_list(b["shards"])}, website: {str(b["website"]).lower()}, '
            f'catalog: {{ forest: {b["catalog"]["forest"]}, caves: {b["catalog"]["caves"]} }} }},' for b in entries]
    lines = ["// Generated by scripts/gen/gen_builds.py from builds.json. Do not edit.",
             "export const GAME_BUILDS = [", *rows, "] as const;",
             'export type GameBuild = (typeof GAME_BUILDS)[number]["number"];',
             f"export const LATEST_BUILD: GameBuild = {latest};",
             "export const WEBSITE_BUILDS: readonly GameBuild[] = "
             "GAME_BUILDS.filter((build) => build.website).map((build) => build.number);",
             f'export const BUILD_NUMBERS_TEXT = "{numbers_text([b["number"] for b in entries])}";']
    return "\n".join(lines) + "\n"


def outputs(staging):
    """{path relative to the root: text} of everything this writes."""
    entries, latest = registry.builds(), registry.latest()
    numbers = [b["number"] for b in entries]
    files = {"seedfinder/data/builds.bend": builds_bend(entries, latest),
             "website/lib/config/game-builds.ts": game_builds_ts(entries, latest)}
    for module, texts in staged(staging, numbers).items():
        if module in SINGLE:
            files[f"seedfinder/data/{module}.bend"] = single(module, texts)
            continue
        found = copies(numbers, {n: copy_text(module, t) for n, t in texts.items()})
        files.update({f"seedfinder/data/b{folder}/{module}.bend": text for folder, text, _ in found})
        files[f"seedfinder/data/{module}.bend"] = dispatch(module, found, latest)
    missing = [m for m in SINGLE if f"seedfinder/data/{m}.bend" not in files]
    assert not missing, f"no staged {missing}"
    return files


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--staging", type=Path, default=registry.ROOT / "build" / "gen" / "data")
    ap.add_argument("--root", type=Path, default=registry.ROOT)
    args = ap.parse_args()
    files = outputs(args.staging)
    data = args.root / "seedfinder" / "data"
    for path in data.rglob("*") if data.is_dir() else []:
        if path.is_file() and str(path.relative_to(args.root)) not in files:
            path.unlink()
    for path, text in files.items():
        (args.root / path).parent.mkdir(parents=True, exist_ok=True)
        (args.root / path).write_text(text, encoding="utf-8")
    for path in sorted(data.glob("*/"), reverse=True):
        if path.is_dir() and not any(path.iterdir()):
            path.rmdir()


if __name__ == "__main__":
    main()
