#!/usr/bin/env python3
"""Generates data/search_vocab.bend: the prefab ids, prefab group names and tile names of catalog.json that parts
B-E of a search config may use (docs/config.md section 3), in catalog order, and the prefabs of cave_catalog.json.
A prefab's vocabulary id is its position in the forest's ids, then in the caves' own ids (the ones the forest lacks).

Run from the project root:
    python3 scripts/gen/gen_search_vocab.py    (writes seedfinder/data/search_vocab.bend; `-` prints it instead)
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CATALOG = ROOT / "scripts" / "catalog" / "catalog.json"
CAVE_CATALOG = ROOT / "scripts" / "catalog" / "cave_catalog.json"
OUTPUT = ROOT / "seedfinder" / "data" / "search_vocab.bend"


def bend_string(text):
    assert text.isascii() and '"' not in text and "\\" not in text, text
    return f'"{text}"'


def string_list(name, doc, values):
    rows = ",\n".join(f"    {bend_string(value)}" for value in values)
    return [f"# {doc}", f"def {name}() -> List<&2, String>:", "  [", rows, "  ]", ""]


def tile_list(tiles):
    rows = ",\n".join(f"    Tile{{{bend_string(tile['name'])}, {'True' if tile['land'] else 'False'}{{}}}}"
                      for tile in tiles)
    return ["# Every catalog tile name with its land flag (TileGroupManager:IsLandTile), in catalog order.",
            "def tiles() -> List<&2, Tile>:", "  [", rows, "  ]", ""]


def group_names(catalog):
    groups = {prefab["group"] for prefab in catalog["prefabs"]}
    return groups | {prefab["variant_of"] for prefab in catalog["prefabs"] if prefab["variant_of"]}


def generate():
    catalog = json.loads(CATALOG.read_text(encoding="utf-8"))
    caves = json.loads(CAVE_CATALOG.read_text(encoding="utf-8"))
    prefabs = [prefab["id"] for prefab in catalog["prefabs"]]
    cave_ids = [prefab["id"] for prefab in caves["prefabs"]]
    cave_only = [prefab for prefab in cave_ids if prefab not in set(prefabs)]
    groups = group_names(catalog)
    lines = ["# Generated by scripts/gen/gen_search_vocab.py; do not edit by hand.", "import Base", "",
             "type Tile is Data:", "  Tile{name: String, land: Bool}", ""]
    lines += string_list("prefabs", "Catalog prefab ids; a prefab's vocabulary id is its position here.", prefabs)
    lines += [f"def prefab_count() -> U32:", f"  {len(prefabs)}", ""]
    lines += string_list("groups", "Catalog group and variant_of names that are not prefab ids.",
                         sorted(groups - set(prefabs)))
    lines += string_list("cave_only", "The caves' own prefab ids: the cave catalog's that the forest catalog lacks; their "
                         "vocabulary ids follow the forest's.", cave_only)
    lines += string_list("cave_prefabs", "Every prefab id of the cave catalog, sorted.", sorted(cave_ids))
    lines += string_list("cave_groups", "The cave catalog's group and variant_of names that are not prefab ids.",
                         sorted(group_names(caves) - set(cave_ids)))
    lines += ["# The name of the vocabulary prefab `id`.", "def prefab_name(+id: U32) -> String:",
              "  Bool.pick(String, (id < prefab_count() : U32),",
              "    Maybe.default(&2, String, List.get(&2, String, prefabs(), U32.to_nat(id)), \"\"),",
              "    Maybe.default(&2, String, List.get(&2, String, cave_only(), U32.to_nat((id - prefab_count() : U32))), \"\"))", "",
              "# Every vocabulary prefab name, by id.", "def all_prefabs() -> List<&2, String>:",
              "  List.append(&2, String, prefabs(), cave_only())", ""]
    lines += tile_list(catalog["tiles"])
    lines += [f"def tile_count() -> U32:", f"  {len(catalog['tiles'])}"]
    return "\n".join(lines) + "\n"


def main():
    text = generate()
    if sys.argv[1:] == ["-"]:
        sys.stdout.write(text)
    else:
        OUTPUT.write_text(text, encoding="utf-8")


if __name__ == "__main__":
    main()
